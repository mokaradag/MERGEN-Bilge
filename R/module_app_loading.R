#' Yükleme Ekranı İstemci Betiği
#' @description Açılış katmanını yöneten satır içi JavaScript metnini döndürür.
#' @return Karakter dizisi (JavaScript)
app_loading_script <- function() {
  paste(
    "(function(){",
    "  'use strict';",
    "  var overlay=document.getElementById('app-loading-overlay');",
    "  if(!overlay) return;",
    "  var STAGES=[",
    "    {key:'boot',label:'Sistem çalıştırılıyor',pct:14},",
    "    {key:'connect',label:'Sunucuya bağlanılıyor',pct:32},",
    "    {key:'auth',label:'Kimlik doğrulanıyor',pct:50},",
    "    {key:'session',label:'Oturumunuz hazırlanıyor',pct:68},",
    "    {key:'workspace',label:'Çalışma alanı hazırlanıyor',pct:86},",
    "    {key:'ready',label:'Neredeyse hazır',pct:97}];",
    "  var stageIndex=-1,finished=false,shinyReady=false;",
    "  var ssoActive=false,ssoResolved=false,skipIntro=false,appReadyAt=0;",
    "  try{var raw=localStorage.getItem('mergen_settings');",
    "    if(raw){var s=JSON.parse(raw);skipIntro=!!(s&&s.skip_intro===true);}",
    "  }catch(e){}",
    "  if(skipIntro){document.documentElement.classList.add('mergen-skip-intro');}",
    "  var statusText=overlay.querySelector('.app-loading-status-text');",
    "  var progressFill=overlay.querySelector('.app-loading-progress-fill');",
    "  function setStage(key){",
    "    var idx=-1;",
    "    for(var i=0;i<STAGES.length;i++){if(STAGES[i].key===key){idx=i;break;}}",
    "    if(idx<0||idx<=stageIndex||finished) return;",
    "    stageIndex=idx;",
    "    if(statusText) statusText.textContent=STAGES[idx].label;",
    "    if(progressFill) progressFill.style.width=STAGES[idx].pct+'%';",
    "  }",
    "  function finish(){",
    "    if(finished) return;",
    "    finished=true;",
    "    if(progressFill) progressFill.style.width='100%';",
    "    overlay.classList.add('app-loading-hidden');",
    "    window.setTimeout(function(){",
    "      if(overlay) overlay.style.display='none';",
    "    },700);",
    "  }",
    "  function welcomeVisible(){",
    "    var root=document.querySelector('.modern-welcome-root');",
    "    return !!(root&&root.offsetParent!==null);",
    "  }",
    "  function evaluate(){",
    "    if(finished) return;",
    "    if(!shinyReady||!ssoResolved) return;",
    "    setStage('workspace');",
    "    if(skipIntro){",
    "      if(welcomeVisible()){setStage('ready');window.setTimeout(finish,600);return;}",
    "      var body=document.body;",
    "      if(body&&body.classList.contains('app-ready')){",
    "        if(!appReadyAt){appReadyAt=Date.now();}",
    "        else if(Date.now()-appReadyAt>2600){",
    "          setStage('ready');window.setTimeout(finish,300);}",
    "      }",
    "    }else{",
    "      setStage('ready');window.setTimeout(finish,550);",
    "    }",
    "  }",
    "  function startSsoWatch(){",
    "    var ssoTimer=window.setInterval(function(){",
    "      if(finished){window.clearInterval(ssoTimer);return;}",
    "      var ssoErr=document.getElementById('sso_module-sso_error');",
    "      if(ssoErr&&window.getComputedStyle(ssoErr).display!=='none'){",
    "        window.clearInterval(ssoTimer);finish();return;}",
    "      var ssoOv=document.getElementById('sso_module-sso_overlay');",
    "      if(ssoOv&&ssoOv.classList.contains('sso-auth-hidden')){",
    "        window.clearInterval(ssoTimer);ssoResolved=true;",
    "        setStage('session');evaluate();}",
    "    },150);",
    "  }",
    "  function detectSso(){",
    "    try{var cfgEl=document.getElementById('sso_module-sso_config_data');",
    "      if(cfgEl){var c=JSON.parse(cfgEl.textContent||'{}');",
    "        ssoActive=!!(c&&c.enabled);}",
    "    }catch(e){}",
    "    if(ssoActive){setStage('auth');startSsoWatch();}",
    "    else{ssoResolved=true;}",
    "    evaluate();",
    "  }",
    "  setStage('boot');",
    "  if(document.readyState==='loading'){",
    "    document.addEventListener('DOMContentLoaded',detectSso);",
    "  }else{detectSso();}",
    "  document.addEventListener('shiny:connected',function(){",
    "    setStage(ssoActive?'auth':'connect');",
    "  });",
    "  document.addEventListener('shiny:sessioninitialized',function(){",
    "    shinyReady=true;",
    "    if(!ssoActive) setStage('session');",
    "    evaluate();",
    "  });",
    "  document.addEventListener('shiny:disconnected',function(){finish();});",
    "  var pollTimer=window.setInterval(function(){",
    "    if(finished){window.clearInterval(pollTimer);return;}",
    "    evaluate();",
    "  },140);",
    "  window.setTimeout(function(){finish();},22000);",
    "  window.MergenAppLoading={finish:finish,setStage:setStage};",
    "})();",
    sep = "\n"
  )
}

