      # satır içi düz renk, stil bloğundaki gradyanı özgüllükle ezerdi.
      style = paste0(
        "position:fixed;top:0;left:0;right:0;bottom:0;z-index:2147483600;",
        "background:",
        "radial-gradient(circle at 50% 34%,rgba(124,77,255,0.20),transparent 56%),",
        "radial-gradient(circle at 50% 104%,rgba(47,109,246,0.16),transparent 60%),",
        "linear-gradient(165deg,#070b1e 0%,#0c1233 50%,#070a18 100%);"
      ),
      tags$div(class = "app-loading-stars"),
      tags$div(class = "app-loading-aurora"),
      tags$div(
        class = "app-loading-stage",
        tags$div(
          class = "app-loading-emblem",
          tags$div(class = "app-loading-ring app-loading-ring-outer"),
          tags$div(class = "app-loading-ring app-loading-ring-mid"),
          tags$div(
            class = "app-loading-orbit",
            tags$span(class = "app-loading-dot app-loading-dot-1"),
            tags$span(class = "app-loading-dot app-loading-dot-2"),
            tags$span(class = "app-loading-dot app-loading-dot-3")
